import assert from 'node:assert/strict'
import { test } from 'node:test'

import {
  describe,
  failing,
  npmFindings,
  pythonFindings,
  unusedAccepted,
  validateAccepted,
  withoutMarkers,
} from './audit.mjs'

// Trimmed from real reports (pip-audit 2.10.1, npm audit format 2).
const PIP = {
  dependencies: [
    { name: 'amqp', version: '5.4.0', vulns: [] },
    {
      name: 'djangorestframework',
      version: '3.18.1',
      vulns: [
        { id: 'CVE-2026-114138', aliases: ['GHSA-33wh-fxxf-88vv'], fix_versions: ['3.18.2'] },
      ],
    },
    {
      // pip-audit lists an advisory once per fixed version
      name: 'certifi',
      version: '2026.7.22',
      vulns: [
        { id: 'PYSEC-2026-4320', aliases: ['GHSA-6q48-6c7w-9gw2'], fix_versions: ['2026.10.18'] },
        { id: 'PYSEC-2026-4320', aliases: ['GHSA-6q48-6c7w-9gw2'], fix_versions: ['2026.10.19'] },
      ],
    },
  ],
  fixes: [],
}

const advisory = (name, ghsa, severity) => ({
  source: 1,
  name,
  dependency: name,
  title: 't',
  url: `https://github.com/advisories/${ghsa}`,
  severity,
  range: '<9',
})

const NPM = {
  auditReportVersion: 2,
  vulnerabilities: {
    vite: {
      name: 'vite',
      severity: 'high',
      via: [advisory('vite', 'GHSA-587h-7wmj-h5pm', 'high'), advisory('vite', 'GHSA-9jrq', 'low')],
    },
    concurrently: { name: 'concurrently', severity: 'critical', via: ['shell-quote'] },
    'shell-quote': {
      name: 'shell-quote',
      severity: 'critical',
      via: [advisory('shell-quote', 'GHSA-pqg4-j6r4-53mv', 'critical')],
    },
  },
  metadata: {},
}

const entry = (fields) => ({ reason: 'no fix yet', accepted_on: '2026-10-28', ...fields })

test('a vulnerable Python package fails, once per advisory', () => {
  const found = pythonFindings(PIP, [])
  assert.deepEqual(
    found.map((f) => [f.package, f.id]),
    [
      ['djangorestframework', 'CVE-2026-114138'],
      ['certifi', 'PYSEC-2026-4320'],
    ],
  )
  assert.equal(failing(found).length, 2)
})

test('a Python advisory is accepted by an alias, with the package name normalized', () => {
  const accepted = [
    entry({ ecosystem: 'pypi', id: 'GHSA-33wh-fxxf-88vv', package: 'DjangoRestFramework' }),
  ]
  const found = pythonFindings(PIP, accepted)
  assert.deepEqual(
    failing(found).map((f) => f.package),
    ['certifi'],
  )
  assert.match(describe(found[0]), /^accepted \(2026-10-28: no fix yet\)/)
})

test('a skipped Python package fails: not checked is not clean', () => {
  const report = { dependencies: [{ name: 'local', version: '1', skip_reason: 'not on PyPI' }] }
  const [found] = pythonFindings(report, [])
  assert.equal(failing([found]).length, 1)
  assert.match(describe(found), /^FAIL skipped pypi .*not on PyPI/)
})

test('environment markers are removed, so other platforms are audited too', () => {
  const exported = [
    '# This file was autogenerated by uv',
    "colorama==0.4.6 ; sys_platform == 'win32' \\",
    '    --hash=sha256:abc',
    "cffi==2.1.1 ; platform_python_implementation != 'PyPy'",
    'django==6.0.1 \\',
    '    --hash=sha256:def',
    '',
  ].join('\n')
  assert.equal(
    withoutMarkers(exported),
    [
      '# This file was autogenerated by uv',
      'colorama==0.4.6 \\',
      '    --hash=sha256:abc',
      'cffi==2.1.1',
      'django==6.0.1 \\',
      '    --hash=sha256:def',
      '',
    ].join('\n'),
  )
})

test('npm: high and critical fail, low is reported only, paths are not advisories', () => {
  const found = npmFindings(NPM, [], 'apps/frontend')
  assert.deepEqual(
    found.map((f) => [f.package, f.id, f.fails]),
    [
      ['vite', 'GHSA-587h-7wmj-h5pm', true],
      ['vite', 'GHSA-9jrq', false],
      ['shell-quote', 'GHSA-pqg4-j6r4-53mv', true],
    ],
  )
  assert.match(describe(found[1]), /^reported only npm apps\/frontend: vite <9 GHSA-9jrq low$/)
})

test('an accepted npm advisory passes and stays listed; unused entries are found', () => {
  const used = entry({ ecosystem: 'npm', id: 'GHSA-pqg4-j6r4-53mv', package: 'shell-quote' })
  const stale = entry({ ecosystem: 'npm', id: 'GHSA-gone', package: 'left-pad' })
  const found = npmFindings(NPM, [used, stale], 'root')
  assert.deepEqual(
    failing(found).map((f) => f.package),
    ['vite'],
  )
  assert.ok(found.some((f) => f.accepted === used))
  assert.deepEqual(unusedAccepted([used, stale], found), [stale])
})

test('an advisory accepted for another package does not match', () => {
  const wrong = entry({ ecosystem: 'npm', id: 'GHSA-pqg4-j6r4-53mv', package: 'vite' })
  assert.equal(failing(npmFindings(NPM, [wrong], 'root')).length, 2)
})

test('malformed reports are errors, never an empty result', () => {
  assert.throws(() => pythonFindings({}, []), /no dependencies list/)
  assert.throws(() => pythonFindings({ dependencies: [{ vulns: [] }] }, []), /unexpected/)
  assert.throws(() => npmFindings({ auditReportVersion: 1 }, [], 'x'), /not format 2/)
  assert.throws(() => npmFindings({ error: { code: 'ENOAUDIT' } }, [], 'x'), /ENOAUDIT/)
  const bad = { auditReportVersion: 2, vulnerabilities: { a: { via: [{ name: 'a' }] } } }
  assert.throws(() => npmFindings(bad, [], 'x'), /unexpected advisory/)
})

test('a valid accepted list has no errors', () => {
  assert.deepEqual(validateAccepted([]), [])
  assert.deepEqual(validateAccepted([entry({ ecosystem: 'npm', id: 'G', package: 'p' })]), [])
})

test('an invalid accepted list is refused with every problem named', () => {
  assert.deepEqual(validateAccepted({}), ['audit-accepted.json must be a JSON list'])
  const errors = validateAccepted([
    entry({ ecosystem: 'maven', id: 'G', package: 'p', note: 'x' }),
    { ecosystem: 'npm', id: 'H', package: 'p', reason: '', accepted_on: '28/10/2026' },
    entry({ ecosystem: 'npm', id: 'H', package: 'p' }),
    'x',
  ])
  assert.deepEqual(errors, [
    'audit-accepted.json[0]: unknown field note',
    'audit-accepted.json[0]: ecosystem must be pypi or npm',
    'audit-accepted.json[1]: reason must be a non-empty string',
    'audit-accepted.json[1]: accepted_on must be a date (YYYY-MM-DD)',
    'audit-accepted.json[2]: H is accepted twice',
    'audit-accepted.json[3]: must be an object',
  ])
})
